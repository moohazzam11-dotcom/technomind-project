// AI Prompt Generator Logic
function generatePrompt() {
    const toolType = document.getElementById('toolType').value;
    const topic = document.getElementById('topicInput').value.trim();
    const style = document.getElementById('styleInput').value;
    const resultBox = document.getElementById('promptResult');

    if (!topic) {
        const lang = document.documentElement.getAttribute('lang') || 'ar';
        resultBox.innerText = lang === 'en' ? "Please enter a topic first!" : "الرجاء كتابة موضوع أولاً!";
        return;
    }

    let prompt = "";

    if (toolType === "chatgpt") {
        const roles = {
            professional: "Act as a senior expert consultant.",
            creative: "Act as a visionary creative writer.",
            funny: "Act as a sarcastic comedian."
        };
        const instruction = `Write a comprehensive guide in Arabic about "${topic}".`;
        const tone = `Ensure the tone is ${style} and engaging.`;

        prompt = `${roles[style]} ${instruction} ${tone} Use clear headings and bullet points.`;
    } else if (toolType === "midjourney") {
        const styles = {
            professional: "photorealistic, 8k, cinematic lighting, professional photography",
            creative: "surrealism, dreamlike, vibrant colors, digital art",
            funny: "cartoon style, caricature, exaggerated features, 2d illustration"
        };

        prompt = `/imagine prompt: ${topic}, ${styles[style]} --ar 16:9 --v 6.0`;
    }

    // Typewriter effect simulation
    resultBox.innerHTML = '';
    const copyBtn = document.createElement('button');
    copyBtn.className = 'copy-btn';
    const lang = document.documentElement.getAttribute('lang') || 'ar';
    copyBtn.innerText = lang === 'en' ? 'Copy' : 'نسخ';
    copyBtn.setAttribute('data-en', 'Copy');
    copyBtn.setAttribute('data-ar', 'نسخ');
    copyBtn.onclick = copyPrompt;
    resultBox.appendChild(copyBtn);

    const textNode = document.createTextNode(prompt);
    resultBox.appendChild(textNode);
}

function copyPrompt() {
    const text = document.getElementById('promptResult').innerText.replace('نسخ', '').trim();
    navigator.clipboard.writeText(text).then(() => {
        const lang = document.documentElement.getAttribute('lang') || 'ar';
        const msg = lang === 'en' ? 'Prompt copied successfully!' : 'تم نسخ الأمر بنجاح!';
        alert(msg);
    });
}

